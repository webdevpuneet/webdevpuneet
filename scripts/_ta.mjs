import fs from 'node:fs';
import { chromium } from 'playwright';
import http from 'node:http';
import { SECTION_TEMPLATES, defaultSectionState } from '../src/components/SectionTemplates/templates/index.js';
import { documentHtml } from '../src/components/SectionTemplates/templates/render.js';
const t = SECTION_TEMPLATES.find(x => x.id === 'team-accordion');
let html = documentHtml(t, defaultSectionState(t), { motion: true });
html = html.replace(/https:\/\/webdevpuneet\.com\/images\/([^"')\s]+)/g, (m, f) => { const p = 'public/images/' + f; return fs.existsSync(p) ? 'data:image/jpeg;base64,' + fs.readFileSync(p).toString('base64') : m; });
const srv = http.createServer((q, r) => { r.writeHead(200, { 'Content-Type': 'text/html' }); r.end(html); });
await new Promise(r => srv.listen(0, '127.0.0.1', r));
const url = 'http://127.0.0.1:' + srv.address().port + '/';
const b = await chromium.launch();
const out = []; const ok = (n, c, x = '') => out.push((c ? 'PASS ' : 'FAIL ') + n + (x ? ' (' + x + ')' : ''));
for (const [label, w] of [['desktop', 1280], ['mobile', 390]]) {
  const p = await b.newPage({ viewport: { width: w, height: 900 } });
  const errs = []; p.on('pageerror', e => errs.push(String(e)));
  await p.goto(url, { waitUntil: 'networkidle' }); await p.waitForTimeout(1500);
  const items = p.locator('.ta-item'); const n = await items.count();
  ok(label + ': 5 strips', n === 5, n);
  ok(label + ': 3rd open at start', (await p.locator('.ta-item.is-open').count()) === 1 && (await items.nth(2).getAttribute('class')).includes('is-open'));
  const grow = i => items.nth(i).evaluate(e => parseFloat(getComputedStyle(e).flexGrow));
  const ext = i => items.nth(i).evaluate((e, ww) => { const r = e.getBoundingClientRect(); return Math.round(ww > 700 ? r.width : r.height); }, w);
  const open0 = await ext(2), closed0 = await ext(0);
  ok(label + ': open strip much bigger', open0 > closed0 * 3, open0 + ' vs ' + closed0);
  ok(label + ': closed photo grayscale', /grayscale/.test(await items.nth(0).locator('.ta-photo img').evaluate(e => getComputedStyle(e).filter)));
  ok(label + ': open photo colour', (await items.nth(2).locator('.ta-photo img').evaluate(e => getComputedStyle(e).filter)) === 'none');
  await items.nth(0).locator('.ta-trigger').click(); await p.waitForTimeout(900);
  ok(label + ': click opens strip 1', (await items.nth(0).getAttribute('class')).includes('is-open') && !(await items.nth(2).getAttribute('class')).includes('is-open'));
  ok(label + ': aria-expanded follows', (await items.nth(0).locator('.ta-trigger').getAttribute('aria-expanded')) === 'true' && (await items.nth(2).locator('.ta-trigger').getAttribute('aria-expanded')) === 'false');
  ok(label + ': strip 1 now big', (await ext(0)) > (await ext(2)) * 3, (await ext(0)) + ' vs ' + (await ext(2)));
  ok(label + ': open info visible, closed hidden', (await items.nth(0).locator('.ta-info').evaluate(e => getComputedStyle(e).visibility)) === 'visible' && (await items.nth(2).locator('.ta-info').evaluate(e => getComputedStyle(e).visibility)) === 'hidden');
  await items.nth(0).locator('.ta-trigger').focus(); await p.keyboard.press('ArrowRight'); await p.waitForTimeout(800);
  ok(label + ': ArrowRight opens next', (await items.nth(1).getAttribute('class')).includes('is-open'));
  ok(label + ': social links in open strip', (await items.nth(1).locator('.ta-social a').count()) >= 1);
  await p.screenshot({ path: process.env.SCR + '/ta-' + label + '.png' });
  ok(label + ': no errors', errs.length === 0, errs.join('|').slice(0, 120));
  await p.close();
}
console.log(out.join('\n')); await b.close(); srv.close();
