/**
 * Writes the lightweight snippet indexes — {id, title, category} rows derived
 * from SNIPPETS, stripped of html/css/js source so they're cheap to bundle
 * into browser-side code:
 *
 *   src/lib/snippet-index.js         every snippet in library order, with
 *                                    `noindex: true` on dev-only ones — used by
 *                                    the sidebar, galleries, header and the
 *                                    editor's Prev / Next.
 *   src/lib/snippet-search-index.js  public snippets only, for homepage search.
 *
 * Browser code must import these (plus UiSnippetsTool/categories.js) instead
 * of UiSnippetsTool/snippets.js, which bundles every snippet's full source.
 * A snippet's own code is loaded on demand by UiSnippetsTool/loadSnippet.js.
 *
 *   node scripts/generate-snippet-search-index.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { SNIPPETS } from '../src/components/UiSnippetsTool/snippets.js';

const ALL_OUT = path.resolve('src/lib/snippet-index.js');
const SEARCH_OUT = path.resolve('src/lib/snippet-search-index.js');

const row = sn => {
  const r = { id: sn.id, title: sn.title, category: sn.category };
  if (sn.noindex) r.noindex = true;
  return r;
};
// One compact row per line: small to bundle, readable in a diff.
const lines = rows => rows.map(r => '  ' + JSON.stringify(r) + ',').join('\n');

const all = SNIPPETS.map(row);
const pub = all.filter(r => !r.noindex);

fs.writeFileSync(ALL_OUT,
`// AUTO-GENERATED by scripts/generate-snippet-search-index.mjs — do not edit by hand.
// Regenerate after adding/removing snippets:  node scripts/generate-snippet-search-index.mjs
// Every snippet as {id, title, category, noindex?}, in library order (oldest
// first) — no html/css/js source, so browser code can bundle it cheaply.

export const SNIPPET_INDEX = [
${lines(all)}
];

// Mirrors VISIBLE_SNIPPETS in UiSnippetsTool/snippets.js: dev-only snippets
// show on localhost, never in production listings.
export const VISIBLE_SNIPPET_INDEX = process.env.NODE_ENV === 'production'
  ? SNIPPET_INDEX.filter(sn => !sn.noindex)
  : SNIPPET_INDEX;
`);

fs.writeFileSync(SEARCH_OUT,
`// AUTO-GENERATED by scripts/generate-snippet-search-index.mjs — do not edit by hand.
// Regenerate after adding/removing snippets:  node scripts/generate-snippet-search-index.mjs
// Public snippets only as {id, title, category}, for homepage search —
// deliberately excludes each snippet's html/css/js source so it's cheap to bundle.

export const SNIPPET_SEARCH_INDEX = [
${lines(pub)}
];
`);

console.log(`✓ Wrote ${all.length} entries to ${path.relative(process.cwd(), ALL_OUT)} and ${pub.length} to ${path.relative(process.cwd(), SEARCH_OUT)}`);
